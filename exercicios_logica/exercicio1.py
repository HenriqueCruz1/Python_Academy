"""Exercício 1: Cálculo de Bônus de Vendas (RH/Vendas): uma empresa decidiu dar um bônus de 10% sobre
 o faturamento total para a equipe de vendas. Calcule o valor do bônus e o faturamento
 final da empresa após subtrair esse bônus.

Faturamento inicial: 50.000
Percentual de bônus: 0.10"""

Faturamento_inicial = 50000
bonus = (Faturamento_inicial/100)*10

print(f"Bonus: {bonus}")
print(f"Atual faturamento inicial após a subtração do bonus: {Faturamento_inicial - bonus}")

